"""Generate docs/API.md from the real FastAPI routes plus captured example responses (network stubbed, mock mode).
    cd backend && python ../scripts/gen_api_docs.py
"""
import json
import os
import sys
from datetime import date
from pathlib import Path

os.environ.update(MOCK_MODE="1", CACHE_TTL_S="0")
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))
from fastapi.testclient import TestClient  # noqa: E402
from app import climate, coach, pestwatch, ratelimit, tools  # noqa: E402
from app.main import app  # noqa: E402

coach._today = lambda: date(2026, 9, 15)
tools.get_weather = lambda place, days=7: {"place": "Kurnool, Andhra Pradesh", "source": "open-meteo.com", "forecast": [
    {"date": "2026-09-16", "max_c": 36, "min_c": 22, "rain_mm": 31.0, "wind_kmh": 20}] * 3}
pestwatch.disease_risk = lambda *a, **k: {"needs_attention": False}
climate._fetch = lambda place, country, s, e: {"place": "Kurnool", "daily": {"time": [(s).isoformat()], "precipitation_sum": [4.0], "temperature_2m_mean": [29.0]}}
c = TestClient(app)

EX = [
    ("POST", "/api/warnings/check", {"crop": "tomato", "place": "Kurnool", "country": "IN", "sowing_date": "2026-08-10", "lang": "en"}),
    ("POST", "/api/buyers/compare", {"offers": [{"buyer": "Trader A", "price": 2400, "commission_pct": 2, "transport_cost": 500, "asks_advance": True}], "quantity": 10, "unit": "quintal", "reference_price": 2300, "currency": "Rs"}),
    ("POST", "/api/outcomes/report", {"records": [{"text": "Apply urea", "kind": "fertilise", "done": True, "useful": True, "predicted": {"expense": 1000}, "actual": {"expense": 1200}}], "lang": "en"}),
    ("POST", "/api/case/build", {"lang": "en", "symptoms": ["spots_on_leaves"], "profile": {"crop": "tomato", "country": "IN"}, "consent": {"share_details": True}}),
    ("POST", "/api/twin/report", {"twin": {"crop": "tomato", "acres": 2, "soil": "sandy", "place": "Kurnool", "sowing_date": "2026-08-01", "expenses": 30000}, "lang": "en"}),
    ("GET", "/api/buyers/registry", None),
]


def short(o, depth=0):
    if isinstance(o, dict):
        return {k: short(v, depth + 1) for k, v in list(o.items())[:14]}
    if isinstance(o, list):
        return [short(v, depth + 1) for v in o[:2]] + (["..."] if len(o) > 2 else [])
    return o[:160] + "..." if isinstance(o, str) and len(o) > 160 else o


L = ["# API reference", "",
     "Generated by `scripts/gen_api_docs.py` from the running FastAPI app. All endpoints are JSON unless noted. No accounts: farmer data lives on the device; "
     "the endpoints below are stateless. Rate limits are per IP per minute (env `RATE_AGENT_PER_MIN`, `RATE_VOICE_PER_MIN`). Interactive docs: `/docs` on a running server.", "",
     "| Method | Path | What it does | Rate limit/min |", "|---|---|---|---|"]
seen = set()
for r in sorted(app.routes, key=lambda r: getattr(r, "path", "")):
    p, ms = getattr(r, "path", ""), getattr(r, "methods", None)
    if not p.startswith("/api") or not ms or p in ("/api/openapi.json",):
        continue
    for m in sorted(ms - {"HEAD", "OPTIONS"}):
        if (m, p) in seen:
            continue
        seen.add((m, p))
        doc = " ".join((r.endpoint.__doc__ or "").split())[:140] or "-"
        lim = next((v for k, v in ratelimit.LIMITS.items() if p.startswith(k)), "none")
        L.append(f"| {m} | `{p}` | {doc} | {lim} |")
L += ["", "## Examples (captured from a real run; network stubbed, so weather and archive values are fixtures)", ""]
for m, p, body in EX:
    ratelimit._hits.clear()
    r = c.post(p, json=body) if m == "POST" else c.get(p)
    L += [f"### {m} `{p}`", ""]
    if body is not None:
        L += ["Request:", "```json", json.dumps(body, indent=2, ensure_ascii=False), "```"]
    L += [f"Response {r.status_code}:", "```json", json.dumps(short(r.json()), indent=2, ensure_ascii=False), "```", ""]
L += ["## Errors", "", "- `400` invalid or missing input (for example `consent.share_details` absent on `/api/case/build`).",
      "- `429` rate limit. `502` model service error or timeout (friendly message, no stack trace). `503` model key not configured.",
      "- Tool and data failures are returned as `{\"error\": ...}` inside the result and shown to the farmer honestly; they never crash a request.", ""]
(ROOT / "docs" / "API.md").write_text("\n".join(L))
print("docs/API.md written", len(L), "lines")
