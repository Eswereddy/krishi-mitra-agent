"""Run every backend test file, build the frontend, and write docs/TEST_REPORT.md from the REAL results.
    python scripts/test_report.py
"""
import re
import subprocess
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
rows, tot_ok, tot_fail = [], 0, 0
for f in sorted((ROOT / "backend" / "tests").glob("test_*.py")):
    t0 = time.time()
    r = subprocess.run([sys.executable, str(f)], capture_output=True, text=True, cwd=ROOT / "backend", timeout=600)
    out = r.stdout + r.stderr
    n_ok = len(re.findall(r"^ok\b", out, re.M))
    src = f.read_text()
    n_def = len(re.findall(r"^def test_", src, re.M))
    passed = r.returncode == 0
    tot_ok += passed
    tot_fail += not passed
    rows.append((f.name, n_def, passed, time.time() - t0, "" if passed else out[-300:].replace("\n", " ")))
fe = subprocess.run(["npm", "run", "build"], capture_output=True, text=True, cwd=ROOT / "frontend", timeout=600)
size = re.search(r"index-[\w-]+\.js\s+([\d.]+ kB) \│ gzip:\s+([\d.]+ kB)", fe.stdout)
sha = subprocess.run(["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True, cwd=ROOT).stdout.strip()
L = ["# Automated test report", "",
     f"Generated by `scripts/test_report.py` on {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')} at commit `{sha}`. Every number is from that run.", "",
     f"- Backend test files: **{tot_ok}/{tot_ok + tot_fail} passing**, {sum(r[1] for r in rows)} test functions in total (run in offline/mock mode with network stubbed).",
     f"- Frontend production build: **{'OK' if fe.returncode == 0 else 'FAILED'}**" + (f", main bundle {size.group(1)} ({size.group(2)} gzip)" if size else ""), "",
     "| Test file | Test functions | Result | Seconds |", "|---|---|---|---|"]
L += [f"| `{n}` | {d} | {'PASS' if p else 'FAIL ' + e} | {s:.1f} |" for n, d, p, s, e in rows]
L += ["", "What these tests do **not** cover: live Meta model behaviour, live Open-Meteo / Agmarknet / WFP responses, real leaf photos, and native-speaker translation quality. "
      "See `EVAL_V2.md` for what is measured offline and what needs a live run.", ""]
(ROOT / "docs" / "TEST_REPORT.md").write_text("\n".join(L))
print("\n".join(L[:8]))
sys.exit(1 if tot_fail or fe.returncode else 0)
